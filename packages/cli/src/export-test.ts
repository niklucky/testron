import { testExecutionMode } from '@testron/protocol';
import { generatePlaywright } from '@testron/domain/codegen/playwright';
import { parsePlaywright, playwrightReplayError } from '@testron/domain/codegen/parse-playwright';
import { annotateExport } from './discovery';
import { CliError } from './files';

// Deliberately contains no server URL, profile values, cookies, or remote storage state.
