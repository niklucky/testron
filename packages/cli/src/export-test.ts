export function exportTestSource(content: TestRevisionContent, id: string, suite: string | null) {
  const source =
    content.source ??
    generatePlaywright(
      content.title,
      content.steps.map(({ payload }) => payload),
    );
  // Never silently discard custom code, hooks, or requests while adapting the target.
  if (playwrightReplayError(source))
    throw new CliError(
      'SOURCE_EXPORT_UNSUPPORTED',
      `Test ${id} contains custom code. Adapt it in the repository before synchronizing; automatic local-target export supports structured Playwright tests.`,
    );
  const parsed = parsePlaywright(source);
  const origins = new Set<string>();
  const steps = parsed.steps.map(({ step }) => {
    if (step.kind !== 'navigate') return step;
    let url: URL;
    try {
      url = new URL(step.url);
    } catch {
      if (step.url.startsWith('/') && !step.url.startsWith('//')) return step;
      throw new CliError(
        'SOURCE_EXPORT_UNSUPPORTED',
        `Test ${id} has an unsupported navigation target.`,
      );
    }
    if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password)
      throw new CliError(
        'SOURCE_EXPORT_UNSUPPORTED',
        `Test ${id} has an unsupported navigation target.`,
      );
    origins.add(url.origin);
    if (url.pathname.startsWith('//'))
      throw new CliError(
        'SOURCE_EXPORT_UNSUPPORTED',
        `Test ${id} has a protocol-relative navigation path. Adapt it explicitly.`,
      );
    return { ...step, url: `${url.pathname}${url.search}${url.hash}` };
  });
  if (origins.size > 1)
    throw new CliError(
      'SOURCE_EXPORT_UNSUPPORTED',
      `Test ${id} navigates multiple origins. Configure local equivalents explicitly before importing.`,
    );
  return annotateExport(
    generatePlaywright(parsed.title, steps).replace(
      "from '@playwright/test'",
      "from './testron.fixture'",
    ),
    id,
    suite,
    testExecutionMode(content),
    Boolean(content.profileId),
    content,
  );
}
